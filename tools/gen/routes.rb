# Dumps the Rails route table (order, verb, path spec, constraints and the
# controller#action) as generated Go, so the Go router matches requests in
# exactly the order Journey does.
require "json"
GO_ROOT = ARGV.fetch(0)

rows = Rails.application.routes.routes.filter_map do |r|
  next if r.app.respond_to?(:app) && r.app.app.is_a?(Class) && !(r.app.app < ActionController::Metal) rescue nil
  defaults = r.defaults
  next unless defaults[:controller]
  reqs = r.requirements.reject { |k, _| %i[controller action].include?(k) }
  {
    verb: r.verb,
    spec: r.path.spec.to_s,
    endpoint: "#{defaults[:controller]}##{defaults[:action]}",
    constraints: reqs.transform_values { |v| v.is_a?(Regexp) ? v.source : v.to_s }
  }
end

body = rows.map do |row|
  cons = row[:constraints].map { |k, v| "#{k.to_s.to_json}: #{v.to_json}" }.join(", ")
  "\t{Verb: #{row[:verb].to_json}, Spec: #{row[:spec].to_json}, Endpoint: #{row[:endpoint].to_json}, Constraints: map[string]string{#{cons}}},"
end.join("\n")

File.write(File.join(GO_ROOT, "internal/web/routes_table.go"), <<~GO)
  // Code generated by tools/gen/routes.rb from the Rails route set; DO NOT EDIT.

  package web

  // RailsRoutes is the Rails route table in recognition order.
  var RailsRoutes = []RouteSpec{
  #{body}
  }
GO
puts "wrote internal/web/routes_table.go (#{rows.size} routes)"
