# Exports the constant tables of the reading resolvers as rb.Map literals.
# Hash keys that are arrays (e.g. [12, 25]) become "12,25"; symbols become
# strings.
require "json"
GO_ROOT = ARGV.fetch(0)

def gs(s)
  s.to_s.to_json.gsub("\\u003c", "<").gsub("\\u003e", ">").gsub("\\u0026", "&")
end

def gkey(k)
  gs(k.is_a?(Array) ? k.join(",") : k)
end

def gv(v)
  case v
  when Hash then "rb.NewMap(#{v.map { |k, x| "rb.KV{K: #{gkey(k)}, V: #{gv(x)}}" }.join(', ')})"
  when Array then "[]any{#{v.map { |x| gv(x) }.join(', ')}}"
  when String, Symbol then gs(v)
  when Integer then "int(#{v})"
  when Float then v.to_s
  when true, false then v.to_s
  when nil then "nil"
  else raise "unsupported #{v.class}"
  end
end

