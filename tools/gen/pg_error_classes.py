#!/usr/bin/env python3
"""Regenerates internal/db/pg_error_classes_gen.go from the pg gem's
ext/errorcodes.def (pass its path)."""
import re
import sys

src = open(sys.argv[1]).read()
seen, lines = set(), []
for block in re.findall(r'\{(.*?)\}', src, re.S):
    m = re.search(r'define_error_class\(\s*"(\w+)"', block)
    if not m:
        continue
    for code in re.findall(r'register_error_class\(\s*"(\w+)"', block):
        if code not in seen:
            seen.add(code)
            lines.append('\t"%s": "PG::%s",' % (code, m.group(1)))
print("// Code generated by tools/gen/pg_error_classes.py from the pg gem's ext/errorcodes.def; DO NOT EDIT.\n")
print("package db\n")
print("// pgErrorClasses maps SQLSTATE codes (and two-character classes) to the pg\n// gem's exception class names.")
print("var pgErrorClasses = map[string]string{")
print("\n".join(lines))
print("}")
